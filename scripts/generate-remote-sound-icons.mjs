import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const constants = await readFile(join(root, 'src/renderer/src/lib/constants.ts'), 'utf8')
const block = constants.match(/export const SOUNDBOARD_ICONS = \[([\s\S]*?)\] as const/)
if (!block) throw new Error('Could not find SOUNDBOARD_ICONS')

const names = [...block[1].matchAll(/'([^']+)'/g)].map((match) => match[1])
const icons = {}
const slugAliases = { Train: 'tram-front' }

for (const name of names) {
  const slug =
    slugAliases[name] ??
    name
      .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
      .replace(/([A-Za-z])([0-9])/g, '$1-$2')
      .toLowerCase()
  const modulePath = join(root, 'node_modules/lucide-react/dist/esm/icons', `${slug}.js`)
  const module = await import(pathToFileURL(modulePath).href)
  if (!module.__iconNode) throw new Error(`Lucide module ${slug} for ${name} has no icon node`)
  icons[name] = module.__iconNode.map(([tag, attributes]) => {
    const svgAttributes = { ...attributes }
    delete svgAttributes.key
    return [tag, svgAttributes]
  })
}

const output = `/* Generated by scripts/generate-remote-sound-icons.mjs. */\nwindow.AMBORA_SOUND_ICONS = ${JSON.stringify(icons)}\n`
await writeFile(join(root, 'remote/sound-icons.js'), output)
